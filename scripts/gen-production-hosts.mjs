// @ts-check
/**
 * Generate `production-hosts.generated.ts` from the upstream `hosts` source.
 *
 * `@notesnook/core`'s `hosts` bag (`vendor/notesnook/packages/core/src/utils/
 * constants.ts`) picks its values via `isProduction()`
 * (`process.env.NODE_ENV === "production" || === "test"`). In `npm run dev`
 * Vite statically defines `process.env.NODE_ENV` as `"development"` in the
 * renderer (a build-time literal that can't be overridden at runtime), so
 * every default host collapses to `http://localhost:…` — where no server runs,
 * so login against the "Notesnook (default)" profile silently fails in dev.
 *
 * Rather than hand-maintain the production URLs (which silently rots when
 * upstream changes a hostname), this script reads the production branch of the
 * upstream `hosts` object straight from the committed submodule source and
 * emits a typed constant the renderer imports. Pull a new upstream rev, re-run
 * this (or `node scripts/build-vendor.mjs`, which calls it), and the default
 * profile picks up the new URLs — no source edits here.
 *
 * The generated file is committed (like `vendor-dist/`) so `npm install` /
 * `npm run dev` / CI work without the submodule checked out (CI does NOT
 * initialise `vendor/notesnook`). A contract test pins the generated file to
 * core's runtime `hosts` (equal under `NODE_ENV=test`) so a stale regen fails
 * CI loudly.
 *
 * Fails loudly (non-zero) if the `hosts` shape changes (a key loses its
 * `isProduction() ? "prod" : "local"` ternary, or a key is added/removed) —
 * forcing a human to look rather than silently emitting wrong/stale hosts.
 *
 * Usage: `node scripts/gen-production-hosts.mjs` (or `npm run gen:hosts`).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(ROOT, "vendor", "notesnook", "packages", "core", "src", "utils", "constants.ts");
const OUT = path.join(ROOT, "apps", "desktop", "src", "renderer", "src", "platform", "production-hosts.generated.ts");

if (!fs.existsSync(SRC)) {
  console.error(`gen-production-hosts: upstream source not found at ${SRC}.`);
  console.error("Check out the vendor/notesnook submodule (git submodule update --init) and re-run.");
  process.exit(1);
}

const source = fs.readFileSync(SRC, "utf8");

// Isolate the `export const hosts = { ... };` block (up to the first `;` after
// the opening brace at the same depth — the object is the only top-level const
// named `hosts`).
const blockMatch = source.match(/export\s+const\s+hosts\s*=\s*\{([\s\S]*?)\};/);
if (!blockMatch) {
  console.error("gen-production-hosts: could not find `export const hosts = { ... };` in constants.ts.");
  console.error("Upstream may have restructured the file — inspect and update this script.");
  process.exit(1);
}
const block = blockMatch[1];

// Expected property keys: every `  WORD:` line in the block.
const expectedKeys = [...block.matchAll(/^\s{2,}(\w+):\s/gm)].map((m) => m[1]);

// Production-branch URLs: `KEY: isProduction() ? "prod" : "local"`.
const ternaryRe = /(\w+):\s*isProduction\(\)\s*\?\s*"([^"]+)"\s*:\s*"([^"]+)"/g;
const found = new Map();
for (const m of block.matchAll(ternaryRe)) {
  found.set(m[1], m[2]);
}

// Loud failure on any shape drift so we never silently emit stale/wrong hosts.
const missing = expectedKeys.filter((k) => !found.has(k));
if (missing.length > 0) {
  console.error("gen-production-hosts: upstream `hosts` shape changed — these keys lost their `isProduction() ? \"prod\" : \"local\"` ternary:");
  for (const k of missing) console.error(`  - ${k}`);
  console.error("Inspect vendor/notesnook/packages/core/src/utils/constants.ts and update this script.");
  process.exit(1);
}
const extra = [...found.keys()].filter((k) => !expectedKeys.includes(k));
if (extra.length > 0) {
  console.error("gen-production-hosts: ternary matched keys not declared as properties (parser bug?):", extra);
  process.exit(1);
}

// Validate every production URL is an absolute http(s) URL.
for (const [k, url] of found) {
  try {
    const u = new URL(url);
    if (u.protocol !== "http:" && u.protocol !== "https:") throw new Error(`bad scheme: ${u.protocol}`);
  } catch (e) {
    console.error(`gen-production-hosts: ${k} production URL is not a valid http(s) URL: ${url} (${e.message})`);
    process.exit(1);
  }
}

// Emit in declaration order (Map preserves insertion order = source order).
const entries = [...found.entries()];
const body = entries.map(([k, v]) => `  ${k}: ${JSON.stringify(v)}`).join(",\n");

const banner = [
  "/**",
  " * DO NOT EDIT — generated by `scripts/gen-production-hosts.mjs` from the",
  " * upstream `hosts` production branch in",
  " * `vendor/notesnook/packages/core/src/utils/constants.ts`.",
  " *",
  " * Regenerate after bumping the upstream submodule:",
  " *   npm run gen:hosts        # or: node scripts/build-vendor.mjs (calls it)",
  " *",
  " * Why this exists: core's `hosts` picks its values via `isProduction()`",
  " * (`process.env.NODE_ENV === \"production\" || === \"test\"`), so in `npm run",
  " * dev` (Vite statically defines `process.env.NODE_ENV` as `\"development\"` in",
  " * the renderer — a build-time literal that can't be overridden at runtime)",
  " * every default host collapses to `http://localhost:…`. Extracting the",
  " * production URLs from the upstream source at vendor-build time keeps the",
  " * \"Notesnook (default)\" profile pointing at the real servers in dev without",
  " * hand-maintaining URLs here. A contract test pins this to core's runtime",
  " * `hosts` (equal under `NODE_ENV=test`) so a stale regen fails CI loudly.",
  " */"
].join("\n");

const out = `${banner}
import { hosts } from "@notesnook-vue/contracts";

type Hosts = typeof hosts;

export const PRODUCTION_HOSTS: Hosts = {
${body}
};
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log(`gen-production-hosts: wrote ${path.relative(ROOT, OUT)} (${entries.length} hosts)`);
for (const [k, v] of entries) console.log(`  ${k} = ${v}`);