#!/usr/bin/env node
/**
 * One-shot generator for `packages/theme-vue/src/defaults.ts`.
 *
 * Reads the built-in `ThemeDark` / `ThemeLight` runtime values from the
 * installed `@notesnook/theme` package (in Node, where React/theme-ui resolve
 * fine) and writes them as typed TS data. The renderer imports this vendored
 * data instead of `@notesnook/theme`, so React + theme-ui + zustand never
 * enter the renderer bundle.
 *
 * Re-run whenever `@notesnook/theme` is bumped:
 *   node scripts/extract-default-themes.mjs
 */
import { createRequire } from "node:module";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const require = createRequire(import.meta.url);
const { ThemeDark, ThemeLight } = require("@notesnook/theme");
// `@notesnook/theme`'s `exports` doesn't expose `./package.json`; read it from
// the resolved package directory instead.
const pkgRoot = resolve(dirname(require.resolve("@notesnook/theme")), "..");
const { version } = JSON.parse(await readFile(resolve(pkgRoot, "package.json"), "utf8"));

const outPath = resolve(process.cwd(), "packages/theme-vue/src/defaults.ts");

const header = `/**
 * Vendored built-in Notesnook themes.
 *
 * GENERATED by scripts/extract-default-themes.mjs — do not edit by hand.
 * Source: @notesnook/theme@${version} (ThemeDark / ThemeLight runtime values).
 * Re-run the script whenever @notesnook/theme is bumped.
 *
 * Vendored (not imported at runtime) so the renderer never pulls
 * @notesnook/theme's React + theme-ui + zustand runtime into the bundle.
 */
import type { ThemeDefinition } from "@notesnook/theme";

`;

const out =
  header +
  // `as ThemeDefinition` (not `: ThemeDefinition =`) because the runtime data
  // omits the deprecated `shade`/`textSelection` colors that the upstream
  // `Colors` type still marks required — an upstream type/data inconsistency.
  // The data is valid against the runtime contract (`validateTheme` only
  // requires the non-deprecated `COLORS`); `buildVariants` derives `shade`
  // itself. The cast bridges the stricter static type.
  `export const ThemeDark = ${JSON.stringify(ThemeDark, null, 2)} as ThemeDefinition;\n\n` +
  `export const ThemeLight = ${JSON.stringify(ThemeLight, null, 2)} as ThemeDefinition;\n`;

await writeFile(outPath, out);
console.log(`wrote ${outPath} (@notesnook/theme@${version})`);